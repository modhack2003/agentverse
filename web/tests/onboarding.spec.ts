import { expect, test } from '@playwright/test'
import { expectNoHorizontalOverflow } from './layout'

const base = 'http://127.0.0.1:8100'

test('fresh setup, password login, settings, backup and connection profile work on mobile', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(base + '/#setup=browser-onboarding-capability')
  expect(page.url()).not.toContain('#setup=')
  await expect(page.getByRole('heading', { name: 'Welcome to AgentVerse' })).toBeVisible()
  await page.getByLabel('User ID', { exact: true }).fill('onboarding-owner')
  await page.getByLabel('Password', { exact: true }).fill('browser-password-123')
  await page.getByLabel('Confirm password').fill('browser-password-123')
  await page.getByLabel('First project name').fill('Guided project')
  await page.getByRole('button', { name: 'Finish setup' }).click()
  await expect(page.getByRole('button', { name: 'App settings' })).toBeVisible()
  await page.getByRole('button', { name: 'App settings' }).click()
  await expect(page.getByRole('heading', { name: 'Installation health' })).toBeVisible()
  const backup = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download workspace backup' }).click()
  expect((await backup).suggestedFilename()).toMatch(/agentverse-backup.*zip/)
  await expectNoHorizontalOverflow(page)
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('button', { name: 'Agents & connections' }).click()
  await page.getByRole('button', { name: 'Connection wizard' }).click()
  await page.getByLabel('Tool kind').selectOption('custom')
  await page.getByLabel('Repository on the agent machine').fill('C:\\Projects\\my repo')
  await page.getByLabel('Verified headless command').fill('["my-tool", "{prompt_file}"]')
  await page.getByLabel('Verified model IDs').fill('provider/test')
  await page.getByRole('button', { name: 'Generate node profile' }).click()
  await expect(page.getByLabel('Node configuration')).toHaveValue(/"provider\/test"/)
  await page.getByRole('button', { name: 'Validate configuration' }).click()
  await page.getByRole('button', { name: 'Check workspace connections' }).click()
  await expect(page.getByRole('status')).toContainText('Workspace authentication: passed')
  await expectNoHorizontalOverflow(page)
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('button', { name: 'Sign out' }).click()
  await expect(page.getByLabel('Login method')).toHaveValue('password')
  await page.getByLabel('User ID', { exact: true }).fill('onboarding-owner')
  await page.getByLabel('Password', { exact: true }).fill('browser-password-123')
  await page.getByRole('button', { name: 'Enter your workspace' }).click()
  await expect(page.getByRole('button', { name: 'App settings' })).toBeVisible()
  expect(errors).toEqual([])
})
