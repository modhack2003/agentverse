  const run = await request.post(`${path}/launch`, { headers }).then(r => r.json())
  await request.post(`${root}/nodes/me/report`, { headers: n.headers, data: { session_id: session, agent_id: a.agent.id, run_id: run.run_id, state: 'unconfirmed', recovery: { journal: 'missing', termination: 'unconfirmed' } } })
  await page.getByRole('button', { name: 'Agents & connections', exact: true }).click()
  await page.getByText('Run recovery evidence', { exact: true }).click()
  await expect(page.locator('.runtime-evidence')).toContainText('Journal availability (last reported): missing')
  await expect(page.locator('.runtime-evidence')).toContainText('Termination evidence (last reported): unconfirmed')
  await expect(page.locator('.runtime-evidence')).toContainText('fixture-v1')
  await expect(page.locator('.runtime-evidence')).toContainText(run.run_id)
  await page.getByRole('button', { name: 'Recover Recovery node token', exact: true }).click()
  await page.getByRole('button', { name: 'Generate replacement node token', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('Stop the node service')
