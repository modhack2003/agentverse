  const p = await setup(page, request, 'Node credentials'), a = await peer(request, p), n = await registeredNode(request, p, { ...profile, mode: 'managed_api', driver: 'http', execution_revision: 'fixture-v1' })
  const path = `${root}/projects/${p.id}/agents/${a.agent.id}`
