test('managed and revoked agent token recovery rejects active runs and retains one-time token on refresh failure', async ({ page, request }) => {
  const p = await setup(page, request, 'Agent credentials'), a = await peer(request, p), n = await registeredNode(request, p, profile)
  const path = `${root}/projects/${p.id}/agents/${a.agent.id}`
  await request.put(`${path}/runtime`, { headers, data: { node_id: n.node.id, profile_id: 'fixture', model: 'fixture-model' } })
  const run = await request.post(`${path}/launch`, { headers }).then(r => r.json())
  await page.getByRole('button', { name: 'Agents & connections', exact: true }).click()
  await page.getByRole('button', { name: 'Replace Recovery peer token', exact: true }).click()
  await page.getByRole('button', { name: 'Generate replacement token', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('Stop or release')
  await request.post(`${path}/stop`, { headers })
  await request.post(`${root}/nodes/me/report`, { headers: n.headers, data: { session_id: session, agent_id: a.agent.id, run_id: run.run_id, state: 'stopped' } })
  await page.route(`**/api/projects/${p.id}/snapshot`, route => route.fulfill({ status: 503, json: { detail: 'Refresh failed' } }))
  await page.getByRole('button', { name: 'Generate replacement token', exact: true }).click()
  const replacement = await page.locator('.copy-box code').textContent()
  expect(replacement).toMatch(/^ac_/)
  expect((await request.get(`${root}/me`, { headers: { Authorization: `Bearer ${a.token}` } })).status()).toBe(401)
  expect((await request.get(`${root}/me`, { headers: { Authorization: `Bearer ${replacement}` } })).ok()).toBeTruthy()
  await page.unroute(`**/api/projects/${p.id}/snapshot`)
  await page.getByRole('button', { name: 'I saved the token' }).click()
  await request.delete(path, { headers })
  await expect(page.getByRole('region', { name: 'Recovery peer agent' })).toContainText('Access revoked')
  await page.getByRole('button', { name: 'Replace Recovery peer token', exact: true }).click()
  await page.getByRole('button', { name: 'Generate replacement token', exact: true }).click()
  await expect(page.locator('.copy-box code')).toContainText('ac_')
})

