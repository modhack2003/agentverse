import { expectNoHorizontalOverflow } from './layout'

const root = 'http://127.0.0.1:8000/api', token = 'browser-test-only-token-not-a-secret'
const headers = { Authorization: `Bearer ${token}` }, session = 'f'.repeat(32)
async function setup(page: Page, request: APIRequestContext, label: string) {
  const name = `${label} ${Date.now()}`
  const p = await request.post(`${root}/projects`, { headers, data: { name, goal: 'Verify optional user flows.', auto_plan: false } }).then(r => r.json())
  await page.goto('/')
  await page.getByLabel('Workspace access token').fill(token)
  await page.getByRole('button', { name: 'Enter your workspace' }).click()
  await page.getByRole('button', { name, exact: true }).click()
  await expect(page.locator('.objective-text')).toContainText('Verify optional user flows.')
  return p
}
async function peer(request: APIRequestContext, p: { id: string }, name = 'Recovery peer') {
  return request.post(`${root}/projects/${p.id}/agents`, { headers, data: { name, kind: 'custom' } }).then(r => r.json())
}
async function registeredNode(request: APIRequestContext, p: { id: string }, profile: unknown) {
  const result = await request.post(`${root}/projects/${p.id}/nodes`, { headers, data: { name: 'Recovery node' } }).then(r => r.json())
  const nodeHeaders = { Authorization: `Bearer ${result.token}` }
  expect((await request.post(`${root}/nodes/me/register`, { headers: nodeHeaders, data: { session_id: session, profiles: [profile] } })).ok()).toBeTruthy()
  return { ...result, headers: nodeHeaders }
}
const profile = { id: 'fixture', name: 'Fixture CLI', kind: 'custom', mode: 'managed_cli', models: [{ id: 'fixture-model', name: 'Fixture model' }] }

test('task editing preserves rejected drafts, edits all fields and rejects claimed work', async ({ page, request }) => {
  const p = await setup(page, request, 'Task editor')
  const dep = await request.post(`${root}/projects/${p.id}/tasks`, { headers, data: { title: 'Dependency' } }).then(r => r.json())
  const task = await request.post(`${root}/projects/${p.id}/tasks`, { headers, data: { title: 'Original task', description: 'Old criteria' } }).then(r => r.json())
  await page.getByRole('button', { name: 'Task board', exact: true }).click()
  await page.getByRole('button', { name: /Original task/ }).click()
  await page.getByRole('button', { name: 'Edit task', exact: true }).click()
  await expect(page.getByLabel('Task title')).toHaveValue('Original task')
  await page.getByLabel('Task title').fill('Edited task')
  await page.getByLabel('Description & acceptance criteria').fill('Updated acceptance criteria')
  await page.getByLabel('Priority', { exact: true }).selectOption('high')
  await page.getByLabel('Required capabilities').fill('python, testing')
  await page.getByLabel('Dependency', { exact: true }).check()
  await page.route(`**/api/projects/${p.id}/tasks/${task.id}`, route => route.fulfill({ status: 503, json: { detail: 'Temporary edit failure' } }))
  await page.getByRole('button', { name: 'Save task' }).click()
  await expect(page.getByRole('alert')).toContainText('Temporary edit failure')
  await expect(page.getByLabel('Task title')).toHaveValue('Edited task')
  await page.unroute(`**/api/projects/${p.id}/tasks/${task.id}`)
  await page.getByRole('button', { name: 'Save task' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  const saved = await request.get(`${root}/projects/${p.id}/tasks`, { headers }).then(r => r.json())
  expect(saved.find((t: { id: string }) => t.id === task.id)).toMatchObject({ title: 'Edited task', description: 'Updated acceptance criteria', priority: 'high', required_capabilities: ['python', 'testing'], dependencies: [dep.id] })
  const a = await peer(request, p)
  await page.getByRole('button', { name: /Dependency/ }).click()
  await page.getByRole('button', { name: 'Edit task', exact: true }).click()
  expect((await request.post(`${root}/projects/${p.id}/tasks/${dep.id}/claim`, { headers: { Authorization: `Bearer ${a.token}` } })).ok()).toBeTruthy()
  await page.getByLabel('Task title').fill('Unsafe claimed edit')
  await page.getByRole('button', { name: 'Save task' }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('Only unclaimed tasks')
  await expect(page.getByLabel('Task title')).toHaveValue('Unsafe claimed edit')
})

test('memory compare and reapply retains draft through a second conflict', async ({ page, request }) => {
  const p = await setup(page, request, 'Memory conflicts')
  const m = await request.post(`${root}/projects/${p.id}/memories`, { headers, data: { title: 'Memory conflict', content: 'Initial memory', tags: ['initial'] } }).then(r => r.json())
  await page.getByRole('button', { name: 'Shared memory', exact: true }).click()
  await page.locator('.memory-card').filter({ hasText: 'Memory conflict' }).click()
  await page.getByLabel('Shared knowledge').fill('My retained draft')
  for (const version of [1, 2]) {
    expect((await request.put(`${root}/projects/${p.id}/memories/${m.id}`, { headers, data: { title: 'Memory conflict', content: `Saved by teammate ${version}`, tags: ['server'], expected_version: version } })).ok()).toBeTruthy()
    await page.getByRole('button', { name: 'Save memory' }).click()
    const comparison = page.getByRole('region', { name: 'Compare conflicting changes' })
    await expect(comparison).toContainText(`Saved by teammate ${version}`)
    await expect(comparison).toContainText('My retained draft')
    await page.setViewportSize({ width: 320, height: 844 })
    await expectNoHorizontalOverflow(page)
    await page.getByRole('button', { name: 'Reapply my draft' }).click()
    await expect(page.getByLabel('Shared knowledge')).toHaveValue('My retained draft')
  }
  await page.getByRole('button', { name: 'Save memory' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  const rows = await request.get(`${root}/projects/${p.id}/memories`, { headers }).then(r => r.json())
  expect(rows[0]).toMatchObject({ content: 'My retained draft', version: 4 })
})

